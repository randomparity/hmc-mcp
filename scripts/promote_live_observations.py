"""Promote completed runner sidecars offline onto a new, unpushed branch.

The caller confirms the final arm and recovery have completed. This command
performs no hardware access and supplies no authorization for a live window.
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from collections import defaultdict
from datetime import UTC, datetime, timedelta
from pathlib import Path
from typing import Any

import check_capability_inventory as inventory
import live_test_runner as runner
from live_test_runner import SUBTASK_GROUPS

ARTIFACTS = frozenset(
    {
        "docs/capabilities/maturity.json",
        "docs/capabilities/release-verification.json",
        "src/hmcpctl/_operation_maturity.json",
    }
)
_BANNER = "<!-- Generated by scripts/gen_tool_reference.py;"


class PromotionError(ValueError):
    """A promotion cannot safely advance; input details remain private."""


def _run(root: Path, *args: str) -> str:
    try:
        result = subprocess.run(
            args,
            cwd=root,
            check=True,
            capture_output=True,
            text=True,
            env={
                **os.environ,
                "GIT_EDITOR": "true",
                "UV_NO_SYNC": "1",
                "PYTHONPATH": str(root / "src"),
            },
        )
    except (OSError, subprocess.CalledProcessError) as error:
        raise PromotionError(
            "local command failed; inspect the checkout before retrying"
        ) from error
    return result.stdout


def _json(path: Path, limit: int) -> Any:
    try:
        if not path.is_file():
            raise PromotionError("input must be a regular JSON file")
        with path.open("rb") as stream:
            raw = stream.read(limit + 1)
        if len(raw) > limit:
            raise PromotionError("input exceeds the supported byte limit")
        return json.loads(raw, object_pairs_hook=inventory._unique_pairs)
    except (OSError, UnicodeError, ValueError, RecursionError) as error:
        raise PromotionError(
            "cannot load input; check JSON shape, encoding and byte limit"
        ) from error


def _regular(root: Path, relative: str) -> None:
    path = root / relative
    if any(
        parent.is_symlink() for parent in [path, *path.parents] if parent != root.parent
    ):
        raise PromotionError("output must not traverse a symlink")
    if not path.is_file():
        raise PromotionError("output must be an existing regular tracked file")


def _allowlist(root: Path) -> set[str]:
    tracked = set(_run(root, "git", "ls-files", "-z").split("\0")) - {""}
    if not ARTIFACTS <= tracked:
        raise PromotionError("required output is not tracked")
    allowed = set(ARTIFACTS)
    for name in tracked:
        if name.startswith("docs/tools/") and name.endswith(".md"):
            _regular(root, name)
            if not (root / name).read_text().startswith(_BANNER):
                raise PromotionError("tool-doc output lacks its generator banner")
            allowed.add(name)
    for name in allowed:
        _regular(root, name)
    return allowed


def _candidate(root: Path, branch: str) -> tuple[str, set[str]]:
    if _run(root, "git", "status", "--porcelain", "--untracked-files=all"):
        raise PromotionError(
            "promotion requires a clean tracked, staged and untracked tree"
        )
    _run(root, "git", "symbolic-ref", "--quiet", "HEAD")
    if not branch.startswith("promotion/"):
        raise PromotionError("choose a new branch below promotion/")
    _run(root, "git", "check-ref-format", "--branch", branch)
    if _run(root, "git", "branch", "--list", branch).strip():
        raise PromotionError("promotion branch already exists; choose a new branch")
    return _run(root, "git", "rev-parse", "HEAD").strip(), _allowlist(root)


def _read_run(path: Path, head: str, now: datetime) -> tuple[dict[str, Any], list]:
    document = _json(path, 16 * 1024 * 1024)
    run = document.get("run") if isinstance(document, dict) else None
    if not isinstance(run, dict):
        raise PromotionError("results lack completed-run provenance")
    arm = run.get("group")
    if (
        not isinstance(arm, str)
        or arm not in SUBTASK_GROUPS
        or run.get("partial") is not False
        or run.get("tree_clean") is not True
        or run.get("tested_commit") != head
        or run.get("detach_probe", False) is not False
        or run.get("subtasks") != SUBTASK_GROUPS[arm]
        or any(type(task) is not int for task in run["subtasks"])
        or not inventory._matches(inventory.SCHEMA_VERSION, run.get("schema_version"))
    ):
        raise PromotionError(
            "run provenance does not describe a complete clean candidate arm"
        )
    try:
        finished = datetime.fromisoformat(run["finished"])
        if finished.utcoffset() != timedelta(0) or finished > now:
            raise ValueError
    except (KeyError, TypeError, ValueError) as error:
        raise PromotionError(
            "run completion time must be a past UTC timestamp"
        ) from error
    sidecar = path.with_name(f"{path.stem}-observations.json")
    rows = _json(sidecar, 1024 * 1024)
    if not isinstance(rows, list) or not rows:
        raise PromotionError("sidecar must be a nonempty observation array")
    return {**run, "finished_time": finished, "results": document.get("results")}, rows


def _evidence(value: dict, run: dict, fingerprint: str, now: datetime) -> None:
    observed = datetime.fromisoformat(value["observed_at"])
    if (
        value["tested_commit"] != run["tested_commit"]
        or value["closure_fingerprint"] != fingerprint
        or observed > run["finished_time"]
        or now - observed > timedelta(days=inventory.STALE_AFTER_DAYS)
    ):
        raise PromotionError(
            "sidecar evidence is stale or disagrees with candidate provenance"
        )


def _rows(
    rows: list, run: dict, fingerprints: dict[str, str], now: datetime
) -> list[dict]:
    identities: set[str] = set()
    sites = inventory.discover_observation_sites()
    for row in rows:
        if not isinstance(row, dict) or set(row) not in (
            {"operation", "observation"},
            {"operation", "missing_scope"},
        ):
            raise PromotionError("sidecar row has an invalid closed shape")
        operation = row["operation"]
        if not isinstance(operation, str) or operation not in fingerprints:
            raise PromotionError("sidecar names an unknown operation")
        errors: list[str] = []
        if "observation" in row:
            value = row["observation"]
            inventory._validate_observation(value, operation, identities, errors)
            if (
                errors
                or value["channel"] != "live"
                or value["schema_version"] != run["schema_version"]
            ):
                raise PromotionError(
                    "sidecar observation fails catalog or run validation"
                )
        else:
            scope = row["missing_scope"]
            inventory._scope_identity(scope, "promotion gap", errors, missing=True)
            if errors or not isinstance(scope, dict) or "confirmation" not in scope:
                raise PromotionError("sidecar gap lacks a valid confirmation")
            value = scope["confirmation"]
        _evidence(value, run, fingerprints[operation], now)
        _invocation(row, run, sites)
    return rows


def _invocation(sidecar: dict, run: dict, sites: dict[tuple[str, int], str]) -> None:
    results = run["results"]
    if not isinstance(results, list) or not results:
        raise PromotionError("results invocation lacks recorded outcomes")
    timestamps = []
    for result in results:
        try:
            timestamp = datetime.fromisoformat(result["timestamp"])
            if (
                timestamp.utcoffset() != timedelta(0)
                or timestamp > run["finished_time"]
                or (timestamps and timestamp < timestamps[-1])
                or type(result["subtask"]) is not int
                or result["subtask"] < 0
                or not isinstance(result["tool"], str)
            ):
                raise ValueError
        except (KeyError, TypeError, ValueError) as error:
            raise PromotionError(
                "results invocation has invalid recording provenance"
            ) from error
        timestamps.append(timestamp)
    observation = sidecar.get("observation")
    value = observation or sidecar["missing_scope"]["confirmation"]
    observed = datetime.fromisoformat(value["observed_at"])
    for index, result in enumerate(results):
        # The producer records the result before its second-resolution sidecar
        # entry, then proceeds to the next result. Keep that exact time interval.
        if (
            not timestamps[index].replace(microsecond=0)
            <= observed
            <= (
                timestamps[index + 1]
                if index + 1 < len(results)
                else run["finished_time"]
            )
        ):
            continue
        tool = result["tool"].split(" (")[0]
        security = runner.TOOL_SECURITY.get(tool)
        if security is not None and security.operation != sidecar["operation"]:
            continue
        if observation:
            if (
                sites.get((sidecar["operation"], result["subtask"]))
                != value["scenario"]
            ):
                continue
            # Some producer labels describe direct commands, not registry tools.
            # Reuse the source-declared release routes for those observations.
            if (
                security is None
                and (sidecar["operation"], run["group"], value["scenario"])
                not in inventory._release_routes()
            ):
                continue
            if (
                runner._observation_id(result["subtask"], result["tool"]) == value["id"]
                and result.get("result") == value["result"]
                and result.get("status")
                == ("PASS" if value["result"] == "passed" else "FAIL")
            ):
                return
        elif (
            security is not None
            and result.get("status") == "SKIP"
            and result.get("result") == "skipped"
        ):
            for module in runner._SCENARIO_MODULES:
                for outcome in vars(module).values():
                    if (
                        isinstance(outcome, runner.ExpectedOutcome)
                        and not outcome.transient
                        and outcome.operation == sidecar["operation"]
                        and outcome.variant == sidecar["missing_scope"]["variant"]
                        and outcome.reason == result.get("note")
                    ):
                        return
    raise PromotionError("sidecar does not match its results invocation")


def _select(options: list[tuple[str, dict]], claim: dict | None) -> dict:
    if claim:
        options = [
            (arm, value)
            for arm, value in options
            if arm == claim["arm"] and value["scenario"] == claim["scenario"]
        ]
    if not options:
        raise PromotionError(
            "claimed operation lacks evidence from its declared arm and scenario"
        )
    newest = max((value["observed_at"], value["id"]) for _, value in options)
    chosen = [
        value for _, value in options if (value["observed_at"], value["id"]) == newest
    ]
    if any(value != chosen[0] for value in chosen):
        raise PromotionError(
            "conflicting observations have the same selection identity"
        )
    if claim and chosen[0]["result"] != "passed":
        raise PromotionError("claimed operation has no eligible passed observation")
    return chosen[0]


def _refuse_weaker(operation: str, evidence: list, observation: dict) -> None:
    # No scenario declares its assertion set, and a passing observation records
    # only the assertions it held; a conditional one can drop out (ST19's
    # refused-while-mounted). The evidence being replaced is the only baseline.
    # A refusal stops the whole window's promotion, by the same rule as every
    # other PromotionError.
    held = set(observation["assertions"])
    for row in evidence:
        if (
            row["channel"] == "live"
            and row["result"] == "passed"
            and observation["result"] == "passed"
            and row["scenario"] == observation["scenario"]
            and held < set(row["assertions"])
        ):
            missing = ", ".join(sorted(set(row["assertions"]) - held))
            raise PromotionError(
                f"passing observation for {operation} lacks assertions held by the "
                f"evidence it would replace: {missing}; rerun the scenario so they "
                "hold, or retire the stored row in a reviewed commit before the window"
            )


def _merge(catalog: dict, observations: dict, gaps: list, claims: list) -> None:
    records = {record["operation"]: record for record in catalog["operations"]}
    by_claim = {claim["operation"]: claim for claim in claims}
    for operation in sorted(observations.keys() | by_claim.keys()):
        if operation not in records and operation in by_claim:
            raise PromotionError(
                "operation needs a reviewed implementation catalog record"
            )
        observation = _select(observations.get(operation, []), by_claim.get(operation))
        if operation not in records:
            print(
                "promotion: omitted unclaimed observation for uncatalogued operation "
                + operation,
                file=sys.stderr,
            )
            continue
        record = records[operation]
        _refuse_weaker(operation, record["evidence"], observation)
        record["evidence"] = [
            row for row in record["evidence"] if row["channel"] != "live"
        ] + [observation]
    for operation, scope in gaps:
        if operation not in records:
            raise PromotionError("gap needs a reviewed implementation catalog record")
        missing = records[operation]["implementation"]["missing_scope"]
        matches = [
            index
            for index, old in enumerate(missing)
            if old["variant"] == scope["variant"]
            and old["parameters"] == scope["parameters"]
        ]
        if len(matches) != 1:
            raise PromotionError("gap needs a matching reviewed missing scope")
        old = missing[matches[0]]
        if (
            old.get("confirmation", {}).get("observed_at", "")
            <= scope["confirmation"]["observed_at"]
        ):
            missing[matches[0]] = scope


def _catalog(
    root: Path, claims: list, results: list[Path], head: str
) -> tuple[dict, str]:
    now = datetime.now(UTC)
    registry = inventory.discover_registry()
    handlers = {tool.operation: tool.handler.rsplit(".", 1)[0] for tool in registry}
    catalog = _json(root / "docs/capabilities/maturity.json", 4 * 1024 * 1024)
    if (
        not isinstance(catalog, dict)
        or set(catalog) != {"format_version", "admission_policy", "operations"}
        or type(catalog["format_version"]) is not int
        or catalog["format_version"] != inventory.MATURITY_FORMAT_VERSION
        or catalog["admission_policy"] != "existing-runtime-guards"
        or not isinstance(catalog["operations"], list)
        or not all(isinstance(row, dict) for row in catalog["operations"])
    ):
        raise PromotionError("candidate catalog has an invalid shape")
    errors: list[str] = []
    inventory._validate_maturity(catalog["operations"], handlers, errors)
    if errors:
        raise PromotionError("candidate catalog fails inventory validation")
    observations: dict[str, list] = defaultdict(list)
    gaps: list = []
    arms: set[str] = set()
    fingerprints: dict[str, str] = {}
    for path in results:
        run, rows = _read_run(path, head, now)
        arm = run["group"]
        if arm in arms:
            raise PromotionError("duplicate arm results are ambiguous")
        arms.add(arm)
        for row in rows:
            if isinstance(row, dict) and isinstance(row.get("operation"), str):
                operation = row["operation"]
                if operation in handlers and operation not in fingerprints:
                    fingerprints[operation] = inventory.closure_fingerprint(
                        root, handlers[operation]
                    )
        for row in _rows(rows, run, fingerprints, now):
            if "observation" in row:
                observations[row["operation"]].append((arm, row["observation"]))
            else:
                gaps.append((row["operation"], row["missing_scope"]))
    if arms != {claim["arm"] for claim in claims}:
        raise PromotionError(
            "results must cover exactly the selected release claim arms"
        )
    _merge(catalog, observations, gaps, claims)
    inventory._validate_maturity(catalog["operations"], handlers, errors)
    if errors:
        raise PromotionError("promoted catalog fails inventory validation")
    snapshot = inventory.render_release_verification(
        catalog["operations"], registry, root, now
    )
    return catalog, snapshot


def _regenerate(root: Path, claims: Path) -> None:
    _run(root, "just", "capability-metadata")
    _run(root, "just", "tool-docs")
    _run(
        root,
        sys.executable,
        "scripts/check_capability_inventory.py",
        "--require-current",
        str(claims),
        "--release",
    )


def _commit(root: Path, allowed: set[str], head: str) -> str:
    changed = set(
        _run(root, "git", "diff", "--name-only", "-z", "HEAD").split("\0")
    ) - {""}
    untracked = _run(root, "git", "ls-files", "--others", "--exclude-standard", "-z")
    if untracked or not changed <= allowed:
        raise PromotionError(
            "generated changes exceed the commit allowlist; inspect the promotion branch"
        )
    for name in changed:
        _regular(root, name)
    if _run(root, "git", "rev-parse", "HEAD").strip() != head:
        raise PromotionError("candidate commit changed during promotion")
    if not changed:
        raise PromotionError("promotion produced no artifact changes")
    _run(root, "git", "add", "--", *sorted(changed))
    staged = set(
        _run(root, "git", "diff", "--cached", "--name-only", "-z").split("\0")
    ) - {""}
    if staged != changed or not staged <= allowed:
        raise PromotionError(
            "index exceeds the commit allowlist; inspect the promotion branch"
        )
    _run(
        root, "git", "commit", "-m", "chore: promote completed live-window observations"
    )
    committed = set(
        _run(
            root,
            "git",
            "diff-tree",
            "--no-commit-id",
            "--name-only",
            "-r",
            "-z",
            "HEAD",
        ).split("\0")
    ) - {""}
    if not committed <= allowed or _run(
        root, "git", "status", "--porcelain", "--untracked-files=all"
    ):
        raise PromotionError(
            "postcommit verification failed; inspect the unpushed promotion branch"
        )
    return _run(root, "git", "rev-parse", "HEAD").strip()


def promote(
    root: Path,
    claims_path: Path,
    branch: str,
    results: list[Path],
    *,
    window_complete: bool,
    recovery_confirmed: bool,
) -> str:
    """Validate a completed window and commit only its generated evidence artifacts."""
    if not window_complete or not recovery_confirmed:
        raise PromotionError(
            "confirm the final arm and clean recovery before promotion"
        )
    root = root.resolve()
    head, allowed = _candidate(root, branch)
    try:
        claims = inventory.load_release_claims(
            claims_path, {tool.operation for tool in inventory.discover_registry()}
        )
        if not claims:
            raise PromotionError("select a nonempty release claims file")
        catalog, snapshot = _catalog(root, claims, results, head)
        if _run(root, "git", "status", "--porcelain", "--untracked-files=all"):
            raise PromotionError(
                "candidate must remain clean before creating the promotion branch"
            )
        _run(root, "git", "switch", "-c", branch)
        inventory.write_runtime_projection(
            root / "docs/capabilities/maturity.json",
            json.dumps(catalog, indent=2) + "\n",
        )
        inventory.write_runtime_projection(
            root / "docs/capabilities/release-verification.json", snapshot
        )
        _regenerate(root, claims_path)
        return _commit(root, allowed, head)
    except (inventory.InventoryError, OSError) as error:
        raise PromotionError(
            "promotion validation or output failed; inspect inputs and checkout"
        ) from error


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--claims", required=True, type=Path)
    parser.add_argument("--branch", required=True)
    parser.add_argument("--window-complete", action="store_true")
    parser.add_argument("--recovery-confirmed", action="store_true")
    parser.add_argument("results", nargs="+", type=Path)
    args = parser.parse_args()
    try:
        commit = promote(
            Path.cwd(),
            args.claims,
            args.branch,
            args.results,
            window_complete=args.window_complete,
            recovery_confirmed=args.recovery_confirmed,
        )
    except PromotionError as error:
        print(f"promotion: {error}", file=sys.stderr)
        return 1
    print(f"promotion committed {commit}; review the local branch before publishing")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
