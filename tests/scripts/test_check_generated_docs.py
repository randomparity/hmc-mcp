def test_banner_naming_a_recipe_outside_the_convention_reddens(
    tmp_path, capsys, monkeypatch
) -> None:
    """The guard runs what the banner names, so the banner may not name `setup`.

    The side effect is checked first and lands on an absolute path. Inside the
    scratch tree it could not be observed at all, and asserting on the message
    first would let the message change mask a banner that actually ran `setup`.
    """
    banner = "<!-- Generated by gen.py; do not edit. Regenerate: just setup -->"
    ran = tmp_path / "setup-ran"
    monkeypatch.setenv("DOC_FRESHNESS_MARKER", str(ran))
    root = _tree(
        tmp_path,
        produced={"page.md": _page("# demo", banner)},
        committed={"page.md": _page("# demo", banner)},
        justfile=JUSTFILE + '\nsetup:\n    touch "$DOC_FRESHNESS_MARKER"\n',
    )

    assert _run(root) == 1
    assert not ran.exists(), "a banner chose what to run against the real environment"
    assert (
        "docs/generated/page.md: first line looks like a generation banner"
        in capsys.readouterr().err
    )


