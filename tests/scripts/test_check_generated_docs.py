"""Tests for the generated-documentation guardrail (scripts/check_generated_docs.py).

Every clause of ADR 0098 §3 gets a negative control here: the guard is only worth
having if each of its failures can be shown to bite. Each control asserts on the
message its own clause emits, not on a substring another clause would also satisfy
-- three of these were vacuous for exactly that reason before review caught it.

The synthetic trees carry a throwaway generator whose output is read from
``pages.json``, so what a command *produces* can be varied independently of what is
*committed*, which is the whole comparison the guard makes.
"""

from __future__ import annotations

import importlib.util
import json
import shutil
import subprocess
import time
from pathlib import Path

import pytest

MODULE_PATH = Path(__file__).parents[2] / "scripts" / "check_generated_docs.py"
MODULE_SPEC = importlib.util.spec_from_file_location(
    "check_generated_docs", MODULE_PATH
)
assert MODULE_SPEC is not None
assert MODULE_SPEC.loader is not None
check_generated_docs = importlib.util.module_from_spec(MODULE_SPEC)
MODULE_SPEC.loader.exec_module(check_generated_docs)

ROOT = Path(__file__).parents[2]

BANNER = "<!-- Generated by gen.py; do not edit. Regenerate: just demo-docs -->"
JUSTFILE = "demo-docs:\n    python3 gen.py\n"
NO_DOCUMENT = "no generated document was found under"
ORPHANED = "no generated document names it"
# Reads what to write from a data file so a test can make the generator and the
# committed tree disagree without editing any code. The nested docs/ read proves the
# guard withholds only the top-level one.
GENERATOR = """\
import json
import pathlib

pages = json.loads(pathlib.Path("pages.json").read_text(encoding="utf-8"))
nested = pathlib.Path("lib/docs/suffix.txt")
suffix = nested.read_text(encoding="utf-8") if nested.is_file() else ""
out = pathlib.Path("docs/generated")
out.mkdir(parents=True, exist_ok=True)
for name, text in pages.items():
    (out / name).write_text(text + suffix, encoding="utf-8")
"""


def _page(body: str, banner: str = BANNER) -> str:
    return f"{banner}\n\n{body}\n"


def _tree(
    tmp_path: Path,
    *,
    produced: dict[str, str] | None = None,
    committed: dict[str, str] | None = None,
    justfile: str = JUSTFILE,
) -> Path:
    """A minimal repository: a justfile, a generator, and a tracked docs tree."""
    healthy = {"page.md": _page("# demo")}
    root = tmp_path / "repo"
    (root / "docs" / "generated").mkdir(parents=True)
    (root / "justfile").write_text(justfile, encoding="utf-8")
    (root / "gen.py").write_text(GENERATOR, encoding="utf-8")
    (root / "pages.json").write_text(
        json.dumps(healthy if produced is None else produced), encoding="utf-8"
    )
    for name, text in (healthy if committed is None else committed).items():
        (root / "docs" / "generated" / name).write_text(text, encoding="utf-8")
    subprocess.run(
        ["git", "init", "-q", "--initial-branch=main"], cwd=root, check=True
    )
    return root


def _stage(root: Path) -> None:
    """Track everything currently in *root*. The guard walks `git ls-files`."""
    subprocess.run(["git", "add", "-A"], cwd=root, check=True, capture_output=True)


def _run(root: Path) -> int:
    """Stage the tree as a developer would, then check it."""
    _stage(root)
    return check_generated_docs.main(["--repo-root", str(root)])


def _tool_reference_only(tmp_path: Path, justfile: str) -> Path:
    """The repository's real justfile and real docs/tools/, and nothing else.

    Enough for the guard to derive recipes and banners from committed production
    configuration. Nothing here can run the real generator, so only tests whose
    regeneration command is stubbed or unreachable may use it.
    """
    root = tmp_path / "repo"
    (root / "docs").mkdir(parents=True)
    (root / "justfile").write_text(justfile, encoding="utf-8")
    shutil.copytree(ROOT / "docs" / "tools", root / "docs" / "tools")
    subprocess.run(
        ["git", "init", "-q", "--initial-branch=main"], cwd=root, check=True
    )
    return root


# --- the committed repository ------------------------------------------------


def test_passes_on_the_committed_repository(capsys) -> None:
    """End to end: run every declared regeneration command and diff the result."""
    assert check_generated_docs.main([]) == 0
    out = capsys.readouterr().out
    assert "`just tool-docs`" in out
    assert str(ROOT / "docs") in out


def test_stubbing_the_real_regeneration_recipe_reddens(tmp_path, capsys) -> None:
    """Negative control on production configuration: `tool-docs: true` reddens.

    The rejected design in #480 asserted that a freshness recipe was *wired*. This
    is the difference: the recipe is still wired, still named by every banner, and
    still runs -- it just does nothing, and that is caught.
    """
    justfile = (ROOT / "justfile").read_text(encoding="utf-8")
    stubbed = justfile.replace(
        "tool-docs:\n    uv run --no-sync python scripts/gen_tool_reference.py\n",
        "tool-docs:\n    true\n",
    )
    assert stubbed != justfile

    assert _run(_tool_reference_only(tmp_path, stubbed)) == 1
    err = capsys.readouterr().err
    assert "docs/tools/index.md: names `just tool-docs`" in err
    assert "did not produce it" in err


def test_deleting_the_real_generated_surface_reddens(tmp_path, capsys) -> None:
    """The other direction on production configuration: no document, orphaned recipe.

    Deleting docs/tools/ and hand-writing a replacement with no banner is the hole
    the rejected design left open; here it empties the walk and orphans `tool-docs`.
    """
    root = _tool_reference_only(tmp_path, (ROOT / "justfile").read_text())
    shutil.rmtree(root / "docs" / "tools")
    (root / "docs" / "tools-summary.md").write_text("# hand written\n", encoding="utf-8")

    assert _run(root) == 1
    err = capsys.readouterr().err
    assert f"'tool-docs' regenerates documentation, but {ORPHANED}" in err
    assert NO_DOCUMENT in err


